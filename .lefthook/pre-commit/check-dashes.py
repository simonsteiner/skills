#!/usr/bin/env python3
"""Fail a commit when a staged, agent-authored file contains an em or en dash.

    check-dashes.py <path>...
    check-dashes.py --help

Meant for a lefthook pre-commit job, given {staged_files}. Em and en dashes are the
punctuation that most marks prose as machine-written, and agents reach for them by habit.
Reads the staged blob (what will be committed, not the working tree); a path the index
doesn't have is ignored. Skipped, because no agent writes them by hand:

- lockfiles, minified bundles, source maps and test snapshots
- tabular and geographic data (*.csv, *.tsv, *.geojson, *.jsonl, ...)
- anything under a vendor/, third_party/, node_modules/ or bower_components/ folder
- binary files: a NUL byte in the first 8000 bytes, or bytes that aren't UTF-8
- files git attributes mark linguist-generated or linguist-vendored (.gitattributes)
- files whose first lines carry a codegen header ("@generated", "DO NOT EDIT", ...)

The same exemptions as check-file-tokens.py, kept standalone so each script is one file.
Prints `path:line:col: em dash` for each one, then how to rewrite them, on stderr.
Exits 0 when no file has one, 1 when any does, 2 on bad usage. Stdlib only.
"""

import argparse
import fnmatch
import os
import re
import subprocess
import sys

# Built from code points so this file passes its own check.
DASHES = {chr(0x2014): "em dash", chr(0x2013): "en dash"}

LOCKFILES = {
    "package-lock.json", "npm-shrinkwrap.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb",
    "go.sum", "go.work.sum", "packages.lock.json", "Package.resolved", "gradle.lockfile",
    ".terraform.lock.hcl", "flake.lock", "Podfile.lock", "pubspec.lock", "composer.lock",
}
NOT_AUTHORED = ("*.lock", "*.lockfile", "*.min.js", "*.min.mjs", "*.min.css", "*.map", "*.snap")
DATA = ("*.csv", "*.tsv", "*.geojson", "*.topojson", "*.jsonl", "*.ndjson", "*.gpx", "*.kml")
VENDOR_DIRS = {"vendor", "third_party", "third-party", "node_modules", "bower_components"}
SNIFF = 8000
GENERATED_PHRASE = (rb"(?:(?i:\s*(?:this (?:file|code) (?:is|was|has been) )?"
                    rb"(?:auto-?generated|generated by|code generated))|.*DO NOT EDIT)")
GENERATED_MARKER = re.compile(rb"(?i:@generated)|^\s*(?:#|//|/\*|\*|<!--|--|;)" + GENERATED_PHRASE, re.MULTILINE)
GENERATED_MARKER_MD = re.compile(rb"(?i:@generated)|^\s*<!--" + GENERATED_PHRASE, re.MULTILINE)
MARKDOWN = (".md", ".markdown", ".mdx")
HEADER_LINES = 5

ADVICE = """\
Em and en dashes read as machine-written. Rewrite each with the punctuation the
sentence needs, without changing what it says:

- a pair around an aside: commas, or parentheses
- before an explanation, a consequence or a list: a colon, a semicolon, or a new sentence
- in a range (1-5, Mon-Fri): a hyphen
- a lone dash meaning "none" in a table: "-" or "none"
- in code that must produce one: an escape (\\u2014) rather than the literal character

A file that must hold them (translations, typography tests) goes in the job's
`exclude:` in lefthook.yml. Don't skip the hook with --no-verify."""


def git(*args, stdin=None):
    return subprocess.run(["git", *args], input=stdin, capture_output=True, check=False)


def staged_blob(path):
    """The staged content of `path`, or None when the index has no file there.

    Read through git only, never open(): git refuses a path outside the repo, so an
    argument like ../../.ssh/id_rsa can't make the script read anything but the index.
    """
    result = git("cat-file", "blob", f":{path}")
    return result.stdout if result.returncode == 0 else None


def marked_by_attributes(paths):
    """Paths .gitattributes (as staged) marks linguist-generated or linguist-vendored."""
    if not paths:
        return set()
    result = git("check-attr", "--cached", "-z", "--stdin", "linguist-generated", "linguist-vendored",
                 stdin=b"\0".join(os.fsencode(p) for p in paths) + b"\0")
    fields = result.stdout.split(b"\0")
    return {os.fsdecode(fields[i]) for i in range(0, len(fields) - 2, 3) if fields[i + 2] in (b"set", b"true")}


def not_authored(path, blob):
    """Whether no agent writes this file by hand, so its dashes aren't ours to fix."""
    name = os.path.basename(path)
    if name in LOCKFILES or any(fnmatch.fnmatch(name, p) for p in NOT_AUTHORED):
        return True
    if any(fnmatch.fnmatch(name.lower(), p) for p in DATA) or VENDOR_DIRS.intersection(path.split("/")[:-1]):
        return True
    if b"\0" in blob[:SNIFF]:
        return True
    marker = GENERATED_MARKER_MD if name.lower().endswith(MARKDOWN) else GENERATED_MARKER
    return bool(marker.search(b"\n".join(blob.split(b"\n", HEADER_LINES)[:HEADER_LINES])))


def dashes(path, blob):
    """`path:line:col: kind` for each dash in a UTF-8 blob; none for one that isn't UTF-8."""
    try:
        text = blob.decode("utf-8")
    except UnicodeDecodeError:
        return []
    return [f"{path}:{n}:{col}: {kind}"
            for n, line in enumerate(text.splitlines(), 1)
            for col, char in enumerate(line, 1)
            if (kind := DASHES.get(char))]


def main(argv):
    parser = argparse.ArgumentParser(
        prog=os.path.basename(sys.argv[0]),
        description="Fail when a staged, agent-authored file contains an em or en dash.",
        epilog="Lockfiles, build output, binaries and generated files are skipped; see the script's docstring.")
    parser.add_argument("paths", nargs="*", help="files to check, normally lefthook's {staged_files}")
    args = parser.parse_args(argv)

    attributed = marked_by_attributes(args.paths)
    found = []
    for path in args.paths:
        blob = None if path in attributed else staged_blob(path)
        if blob is not None and not not_authored(path, blob):
            found += dashes(path, blob)

    if found:
        print("\n".join(found) + "\n\n" + ADVICE, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
