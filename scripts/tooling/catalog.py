"""The skill catalogs: README.md, each bucket README, plugin.json and third-party/README.md.

Every listing of skills is derived from the skills themselves, or for curated skills from
third-party/skills.json, so it can't drift:

- README.md and each skills/<bucket>/README.md hold a generated block between
  START and END. Each entry is `- **[name](path/to/SKILL.md)**: summary`, grouped
  under User-invoked and Model-invoked by the skill's `disable-model-invocation`.
  README.md lists the published buckets (engineering/, productivity/, misc/); a
  bucket README lists its own skills. Prose outside the block is hand-written.
- .claude-plugin/plugin.json lists every published skill folder; its other keys are kept.
- third-party/README.md holds a generated block with one section per source in
  skills.json: the source's `why`, an entry per curated skill linking its upstream SKILL.md
  with the first sentence of its `why`, grouped under User-invoked and Model-invoked by its
  `invocation`, and its archived skills with their full reasons, collapsed.

A skill's summary comes from its frontmatter `description`. A user-invoked description
is already a human-facing summary, so it's used whole; a model-invoked one ends its
summary where its trigger phrasing starts, at the first sentence beginning "Use"
("Use when…", "Use before…"), so it must have one (docs/invocation.md).

scripts/build-catalog.py writes the files; lint-skills.py runs stale() through
published_rules.py. tests/tooling/test_catalog.py tests it.
"""

import json
import re

from . import third_party
from .skill_inventory import PUBLISHED

START = "<!-- skill-catalog:start: generated by scripts/build-catalog.py; edit the skills or third-party/skills.json, not this list -->"
END = "<!-- skill-catalog:end -->"
GROUPS = ("User-invoked", "Model-invoked")
PLUGIN = ".claude-plugin/plugin.json"
TRIGGERS = re.compile(r"(?<=[.!?])\s+(?=Use\b)")
SENTENCE = re.compile(r"(?<=[.!?])\s+(?=[A-Z`\"(])")
THIRD_PARTY = "third-party/README.md"


def summary(skill):
    """The catalog line's text for `skill`, or None when its description has no summary to take."""
    desc = (skill.fields or {}).get("description")
    if not isinstance(desc, str) or not desc.strip():
        return None
    desc = " ".join(desc.split())
    if not skill.model_invoked:
        return desc
    parts = TRIGGERS.split(desc, maxsplit=1)
    return parts[0] if len(parts) == 2 else None


def problems(skills, repo):
    """Skills whose description yields no catalog summary."""
    def described(s):  # an empty or non-string description is authoring_rules.py's to report
        desc = (s.fields or {}).get("description")
        return isinstance(desc, str) and desc.strip()

    return [
        f"{s.skill_md.relative_to(repo).as_posix()}: model-invoked description needs a summary before "
        'a sentence starting "Use" ("Use when…"); the catalog lists that summary'
        for s in skills if described(s) and summary(s) is None
    ]


def _groups(skills, level, link):
    """Markdown lines: a `level` heading per non-empty group, then one entry per skill, by name."""
    lines = []
    for model_invoked, group in enumerate(GROUPS):
        members = sorted((s for s in skills if s.model_invoked == bool(model_invoked)), key=lambda s: s.name)
        if not members:
            continue
        lines += [f"{'#' * level} {group}", ""]
        lines += [f"- **[{s.name}]({link(s)})**: {summary(s) or ''}".rstrip() for s in members]
        lines.append("")
    return lines


def readme_block(skills, repo):
    """The generated block of the top-level README.md: one section per published bucket."""
    lines = []
    for bucket in PUBLISHED:
        members = [s for s in skills if s.bucket == bucket]
        if members:
            lines += [f"### {bucket.capitalize()}", ""]
            lines += _groups(members, 4, lambda s: f"./{s.skill_md.relative_to(repo).as_posix()}")
    return lines


def bucket_block(skills, bucket):
    """The generated block of skills/<bucket>/README.md."""
    return _groups([s for s in skills if s.bucket == bucket], 2, lambda s: f"./{s.name}/SKILL.md")


def upstream(curated):
    """The URL of a curated skill's SKILL.md on its repo's default branch."""
    folder = curated.path.strip("/")
    folder = "" if folder in ("", ".") else f"{folder}/"
    return f"https://github.com/{curated.repo}/blob/HEAD/{folder}SKILL.md"


def third_party_block(manifest):
    """The generated block of third-party/README.md: one section per source, in manifest order."""
    lines = []
    for source in manifest.sources:
        lines += [f"### [{source.repo}](https://github.com/{source.repo})", ""]
        if source.why.strip():
            lines += [" ".join(source.why.split()), ""]
        for invocation, group in zip(("user", "model"), GROUPS):
            members = [k for k in source.skills if (k.invocation or "model") == invocation]
            if not members:
                continue
            lines += [f"#### {group}", ""]
            for k in members:
                first = SENTENCE.split(" ".join(k.why.split()), maxsplit=1)[0]
                lines.append(f"- **[{k.name}]({upstream(k)})**: {first}".rstrip(": "))
            lines.append("")
        if source.archived:
            lines += ["<details>", f"<summary>Archived ({len(source.archived)})</summary>", ""]
            lines += [f"- **[{k.name}]({upstream(k)})**: {' '.join(k.why.split())}".rstrip(": ")
                      for k in source.archived]
            lines += ["", "</details>", ""]
    return lines


def splice(text, lines):
    """`text` with its generated block replaced by `lines`, or None when it has no block."""
    start, end = text.find(START), text.find(END)
    if start < 0 or end < start:
        return None
    body = "\n".join(lines).strip("\n")
    return f"{text[:start]}{START}\n\n{body}\n\n{text[end:]}" if body else f"{text[:start]}{START}\n{text[end:]}"


def plugin(text, skills, repo):
    """plugin.json's text with `skills` set to every published skill folder, by path."""
    data = json.loads(text)
    data["skills"] = sorted(f"./{s.folder.relative_to(repo).as_posix()}" for s in skills if s.published)
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def bucket_readmes(skills, repo):
    """Every bucket README the catalog writes: buckets with skills, and ones an emptied bucket left."""
    buckets = {s.bucket for s in skills} | {p.parent.name for p in repo.glob("skills/*/README.md")}
    return {repo / "skills" / b / "README.md": b for b in sorted(buckets)}


def render(skills, repo):
    """{path: (current text or None, rendered text or None)} for every catalog file.

    Rendered is None when the file exists but has no generated block to fill.
    A missing bucket README is rendered as a title and an empty block.
    """
    out = {}
    readme = repo / "README.md"
    current = readme.read_text() if readme.exists() else None
    out[readme] = (current, current and splice(current, readme_block(skills, repo)))
    for path, bucket in bucket_readmes(skills, repo).items():
        current = path.read_text() if path.exists() else None
        base = current if current is not None else f"# {bucket.capitalize()}\n\n{START}\n{END}\n"
        out[path] = (current, splice(base, bucket_block(skills, bucket)))
    path = repo / PLUGIN
    current = path.read_text() if path.exists() else None
    out[path] = (current, current and plugin(current, skills, repo))
    manifest = third_party.load(repo)
    if manifest is not None:
        path = repo / THIRD_PARTY
        current = path.read_text() if path.exists() else None
        out[path] = (current, current and splice(current, third_party_block(manifest)))
    return out


def stale(skills, repo):
    """What's out of date in the catalog files, as messages."""
    found = []
    for path, (current, rendered) in render(skills, repo).items():
        where = path.relative_to(repo).as_posix()
        if current is None:
            found.append(f"{where} is missing" + ("; run scripts/build-catalog.py" if rendered else ""))
        elif rendered is None:
            found.append(f"{where} has no generated skill catalog: add the {START!r} and {END!r} lines")
        elif rendered != current:
            found.append(f"{where}: the skill catalog is out of date; run scripts/build-catalog.py")
    return found


def write(skills, repo):
    """Write every catalog file that changed; return the paths written."""
    written = []
    for path, (current, rendered) in render(skills, repo).items():
        if rendered is not None and rendered != current:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered)
            written.append(path)
    return written
