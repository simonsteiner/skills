"""Tests for skills/engineering/setup-lefthook/scripts/check-dashes.py, against throwaway repos.

    uv run --locked --no-build python3 -m unittest discover -s tests -t .
"""

import os
import subprocess
import tempfile
import unittest
from pathlib import Path

from tests.skill_scripts.staged_repo import ENV, StagedRepoTest

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "skills/engineering/setup-lefthook/scripts/check-dashes.py"
# What the lefthook remote (lefthook/hooks.yml) ships to other repos.
REMOTE_COPY = ROOT / ".lefthook/pre-commit/check-dashes.py"

EM, EN = chr(0x2014), chr(0x2013)
DASHED = f"an aside {EM} here\n"


class CheckDashesTest(StagedRepoTest):
    def run_script(self, *paths):
        return subprocess.run([str(SCRIPT), *paths], cwd=self.repo, env=ENV,
                              capture_output=True, text=True, check=False)

    def flagged(self, *paths):
        return [line for line in self.run_script(*paths).stderr.splitlines() if line.endswith(" dash")]

    def test_reports_each_dash_with_its_position_and_how_to_fix_it(self):
        self.stage("a.md", f"fine\nan aside {EM} here, pages 1{EN}5\n")
        result = self.run_script("a.md")
        self.assertEqual(result.returncode, 1)
        self.assertEqual(self.flagged("a.md"), ["a.md:2:10: em dash", "a.md:2:25: en dash"])
        self.assertIn("a hyphen", result.stderr)

    def test_files_without_dashes_pass(self):
        self.stage("a.md", "a hyphen - and a range 1-5\n")
        result = self.run_script("a.md")
        self.assertEqual((result.returncode, result.stderr), (0, ""))

    def test_no_files_pass(self):
        self.assertEqual(self.run_script().returncode, 0)

    def test_checks_the_staged_content_not_the_working_tree(self):
        self.stage("a.md", "clean\n")
        (self.repo / "a.md").write_text(DASHED, encoding="utf-8")
        self.assertEqual(self.run_script("a.md").returncode, 0)
        self.stage("b.md", DASHED)
        (self.repo / "b.md").write_text("clean\n", encoding="utf-8")
        self.assertEqual(self.flagged("b.md"), ["b.md:1:10: em dash"])

    def test_files_no_agent_writes_are_skipped(self):
        skipped = ["package-lock.json", "dist/app.min.js", "data/people.csv", "vendor/lib/x.py",
                   "gen.py", "README.md"]
        for path in skipped[:4]:
            self.stage(path, DASHED)
        self.stage("gen.py", f"# Code generated by protoc. DO NOT EDIT.\n{DASHED}")
        self.stage("README.md", f"<!-- auto-generated by docs.py -->\n{DASHED}")
        self.assertEqual(self.run_script(*skipped).returncode, 0)

    def test_binary_and_non_utf8_files_are_skipped(self):
        self.stage("a.bin", b"\0" + DASHED.encode())
        self.stage("b.txt", b"\xff\xfe" + DASHED.encode("utf-16-le"))
        self.assertEqual(self.run_script("a.bin", "b.txt").returncode, 0)

    def test_gitattributes_marks_generated_and_vendored_files(self):
        self.stage(".gitattributes", "CHANGELOG.md linguist-generated\nlib/** linguist-vendored\n")
        self.stage("CHANGELOG.md", DASHED)
        self.stage("lib/x.js", DASHED)
        self.stage("src/x.js", DASHED)
        self.assertEqual(self.flagged("CHANGELOG.md", "lib/x.js", "src/x.js"), ["src/x.js:1:10: em dash"])

    def test_a_path_outside_the_repo_is_not_read(self):
        with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False, encoding="utf-8") as f:
            f.write(DASHED)
        self.addCleanup(os.unlink, f.name)
        self.assertEqual(self.run_script(f.name, "missing.md").returncode, 0)

    def test_the_remote_copy_matches_the_skill_script(self):
        # lefthook finds a remote's scripts in <remote>/.lefthook/<hook>/; a symlink there
        # would check out as a text file on Windows, so it's a copy this test keeps identical.
        self.assertFalse(REMOTE_COPY.is_symlink())
        self.assertEqual(REMOTE_COPY.read_bytes(), SCRIPT.read_bytes(), "copy the skill script to " + str(REMOTE_COPY))
        self.assertTrue(os.access(REMOTE_COPY, os.X_OK))


if __name__ == "__main__":
    unittest.main()
